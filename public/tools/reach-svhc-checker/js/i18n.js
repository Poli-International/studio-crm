function getLanguage() {
  try {
    const saved = localStorage.getItem("poli_tools_language");
    if (saved && I18N_DICTIONARIES[saved]) return saved;
  } catch (e) {}
  if (typeof navigator !== "undefined" && navigator.language) {
    const navLang = navigator.language.slice(0, 2).toLowerCase();
    if (I18N_DICTIONARIES[navLang]) return navLang;
  }
  return "en";
}

function setLanguage(lang) {
  if (I18N_DICTIONARIES[lang]) {
    try {
      localStorage.setItem("poli_tools_language", lang);
    } catch (e) {}
    // Screen readers and the browser's translate prompt read <html lang>.
    if (typeof document !== "undefined") document.documentElement.lang = lang;
    return lang;
  }
  return "en";
}

function t(key, params = {}) {
  const lang = getLanguage();
  const dict = I18N_DICTIONARIES[lang] || I18N_DICTIONARIES.en;
  let text = dict[key] || I18N_DICTIONARIES.en[key] || key;
  for (const [pKey, pVal] of Object.entries(params)) {
    text = text.replace(new RegExp("\{" + pKey + "\}", "g"), pVal);
  }
  return text;
}

if (typeof window !== "undefined") {
  window.I18N_DICTIONARIES = I18N_DICTIONARIES;
  window.getLanguage = getLanguage;
  window.setLanguage = setLanguage;
  window.t = t;
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { I18N_DICTIONARIES, getLanguage, setLanguage, t };
}
